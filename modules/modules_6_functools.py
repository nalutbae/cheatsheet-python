print("=" * 5, "lru_cache: memoization with least-recently-used eviction", "=" * 5)

# Basic lru_cache
@lru_cache(maxsize=128)
def fibonacci(n):
    if n <= 1:
        return n
    return fibonacci(n - 1) + fibonacci(n - 2)

print(f"Fibonacci(50): {fibonacci(50)}")  # 12586269025 (instant!)

# Check cache info
print(f"Cache info: {fibonacci.cache_info()}")  # hits, misses, maxsize, currsize

# Clear cache
fibonacci.cache_clear()
print(f"After clear: {fibonacci.cache_info()}")

