print("=" * 5, "reduce: cumulative application", "=" * 5)

# Sum using reduce
numbers = [1, 2, 3, 4, 5]
total = reduce(lambda a, b: a + b, numbers)
print(f"Sum: {total}")  # 15

# Product using reduce
product = reduce(lambda a, b: a * b, numbers)
print(f"Product: {product}")  # 120

# Reduce with initial value
total_with_init = reduce(lambda a, b: a + b, numbers, 100)
print(f"Sum with initial 100: {total_with_init}")  # 115

# Find maximum using reduce
maximum = reduce(lambda a, b: a if a > b else b, numbers)
print(f"Max: {maximum}")  # 5

# Flatten a list of lists
lists = [[1, 2], [3, 4], [5, 6]]
flat = reduce(lambda a, b: a + b, lists)
print(f"Flatten: {flat}")  # [1, 2, 3, 4, 5, 6]

